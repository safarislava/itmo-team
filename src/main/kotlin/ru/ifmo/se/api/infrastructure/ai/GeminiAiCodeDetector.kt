package ru.ifmo.se.api.infrastructure.ai

import org.slf4j.LoggerFactory
import org.springframework.beans.factory.annotation.Value
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty
import org.springframework.http.MediaType
import org.springframework.http.client.SimpleClientHttpRequestFactory
import org.springframework.stereotype.Component
import org.springframework.web.client.RestClient
import org.springframework.web.client.body
import ru.ifmo.se.api.application.port.out.AiCodeDetector
import tools.jackson.databind.ObjectMapper
import java.time.Duration

@Component
@ConditionalOnProperty(name = ["app.ai-detector.enabled"], havingValue = "true")
class GeminiAiCodeDetector(
    @Value("\${app.ai-detector.gemini.api-key}") private val apiKey: String,
    @Value("\${app.ai-detector.gemini.model}") private val model: String,
    private val objectMapper: ObjectMapper,
) : AiCodeDetector {
    private val restClient =
        RestClient
            .builder()
            .baseUrl("https://generativelanguage.googleapis.com/v1beta/models")
            .requestFactory(
                SimpleClientHttpRequestFactory().apply {
                    setConnectTimeout(Duration.ofSeconds(5))
                    setReadTimeout(Duration.ofSeconds(15))
                },
            ).build()

    override fun detect(
        sourceCode: String,
        languageName: String,
    ): Short? {
        if (apiKey.isBlank()) return null
        if (sourceCode.trim().length < MIN_CODE_LENGTH) return 0

        val prompt =
            """
            Task: Determine if this competitive programming $languageName code was written by a HUMAN or generated by AI.

            CRITICAL FACTS:
            - Standard competitive programming techniques (fast I/O like ios_base::sync_with_stdio(false) or sys.stdin.read, short variables like n, k, a, pref, ans, and compact language idioms) are CLASSIC HUMAN patterns. They are NOT evidence of AI. Normal competitive code should score 0-20.
            - Evidence of AI is: tutorial/step-by-step comments ("Step 1", "Time complexity"), unprompted defensive checks not required by competitive problem statements, or textbook explanatory style.

            Code to analyze:
            ```$languageName
            $sourceCode
            ```
            """.trimIndent()

        val payload =
            mapOf(
                "contents" to listOf(mapOf("parts" to listOf(mapOf("text" to prompt)))),
                "generationConfig" to
                    mapOf(
                        "responseMimeType" to "application/json",
                        "responseSchema" to
                            mapOf(
                                "type" to "OBJECT",
                                "properties" to
                                    mapOf(
                                        "analysis" to
                                            mapOf(
                                                "type" to "STRING",
                                                "description" to "1 sentence explanation.",
                                            ),
                                        "aiScore" to
                                            mapOf(
                                                "type" to "INTEGER",
                                                "description" to "0-100 probability.",
                                            ),
                                    ),
                                "required" to listOf("analysis", "aiScore"),
                            ),
                    ),
            )

        return runCatching {
            val response =
                restClient
                    .post()
                    .uri("/$model:generateContent?key=$apiKey")
                    .contentType(MediaType.APPLICATION_JSON)
                    .body(payload)
                    .retrieve()
                    .body<GeminiResponse>()

            val innerJson =
                response
                    ?.candidates
                    ?.firstOrNull()
                    ?.content
                    ?.parts
                    ?.firstOrNull()
                    ?.text ?: return null

            objectMapper
                .readValue(innerJson, AiResult::class.java)
                .aiScore
                ?.toInt()
                ?.coerceIn(0, 100)
                ?.toShort()
        }.getOrNull()
    }

    private data class GeminiResponse(
        val candidates: List<Candidate>? = null,
    )

    private data class Candidate(
        val content: Content? = null,
    )

    private data class Content(
        val parts: List<Part>? = null,
    )

    private data class Part(
        val text: String? = null,
    )

    private data class AiResult(
        val analysis: String? = null,
        val aiScore: Short? = null,
    )

    private companion object {
        private const val MIN_CODE_LENGTH = 50
    }
}
